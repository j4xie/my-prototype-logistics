class TestNextIntRejection:
    @pytest.mark.parametrize("bound", [3, 5, 7, 100, 1024])
    def test_seed_zero_sequence(self, bound, java_reference):
        seq = java_reference["random_sequences"][0]
        assert seq["seed"] == 0
        expected = seq[f"next_int_{bound}"]
        rng = _JavaRandom(0)
        actual = [rng.next_int(bound) for _ in range(len(expected))]
        assert actual == expected

    def test_all_seeds_all_bounds(self, java_reference):
        """Sweep every seed × every recorded bound. Catches LCG state drift."""
        bounds_to_check = [2, 3, 5, 7, 8, 16, 100, 1024]
        mismatches = []
        for seq in java_reference["random_sequences"]:
            seed = seq["seed"]
            for bound in bounds_to_check:
                expected = seq[f"next_int_{bound}"]
                rng = _JavaRandom(seed)
                actual = [rng.next_int(bound) for _ in range(len(expected))]
                if actual != expected:
                    mismatches.append({"seed": seed, "bound": bound,
                                       "expected": expected[:5],
                                       "actual": actual[:5]})
        assert not mismatches, f"next_int mismatches: {mismatches[:3]}"


