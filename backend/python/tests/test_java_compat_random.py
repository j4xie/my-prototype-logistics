# _JavaRandom — initialization + invariants
# ---------------------------------------------------------------------------


class TestJavaRandomInit:
    def test_seed_xor_scramble(self):
        # JDK source: this.seed = (seed ^ 0x5DEECE66DL) & MASK
        rng = _JavaRandom(0)
        assert rng.seed == (0 ^ 0x5DEECE66D) & ((1 << 48) - 1)

    def test_seed_int_overflow_handled(self):
        # Negative seeds (e.g. hash codes for "RES_3101_001" = -126594128)
        # must not crash and must produce same output as Java new Random(-126594128).
        rng = _JavaRandom(-126594128)
        # next() should return some valid 31-bit int
        v = rng._next(31)
        assert 0 <= v < (1 << 31)


# ---------------------------------------------------------------------------
# _JavaRandom.next_int — power-of-2 fast path
# ---------------------------------------------------------------------------


class TestNextIntPowerOfTwo:
    @pytest.mark.parametrize("bound", [1, 2, 8, 16])
    def test_seed_zero_sequence(self, bound, java_reference):
        seq = java_reference["random_sequences"][0]  # seed=0
        assert seq["seed"] == 0
        expected = seq[f"next_int_{bound}"]
        rng = _JavaRandom(0)
        actual = [rng.next_int(bound) for _ in range(len(expected))]
        assert actual == expected

    def test_bound_one_always_zero(self):
        # JDK fast path: bound is power of 2 → (bound * _next(31)) >> 31
        # For bound=1, that's _next(31) >> 31, always 0 (31-bit value shifted right 31).
        rng = _JavaRandom(42)
        assert all(rng.next_int(1) == 0 for _ in range(20))


