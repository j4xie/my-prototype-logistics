# Production / quality mock-generator usage pattern
# ---------------------------------------------------------------------------


class TestMockGeneratorPattern:
    """Verifies the 7-call-per-record consumption order used by Java's
    generateMockProductionData / generateMockQualityData. Order:

        1. nextInt(8)      — plannedRuntime offset
        2. nextDouble()    — downtime raw value
        3. nextInt(100)    — theoreticalOutput offset
        4. nextDouble()    — actualOutput multiplier
        5. nextDouble()    — goodUnits multiplier
        6. nextInt(3)      — failureCount
        7. nextInt(5)      — downtimeReason index
    """

    def test_seed_zero_five_records(self, java_reference):
        seq = java_reference["random_sequences"][0]
        assert seq["seed"] == 0
        rng = _JavaRandom(0)
        for i, expected in enumerate(seq["mixed_records_5"]):
            assert rng.next_int(8) == expected["plannedRuntime"], f"rec {i} plannedRuntime"
            d_actual = rng.next_double()
            d_expected = _hex_bits_to_double(expected["downtime"])
            assert struct.pack(">d", d_actual) == struct.pack(">d", d_expected), \
                f"rec {i} downtime"
            assert rng.next_int(100) == expected["theoreticalOutput"], f"rec {i} theoreticalOutput"
            am_actual = rng.next_double()
            am_expected = _hex_bits_to_double(expected["actualOutputMult"])
            assert struct.pack(">d", am_actual) == struct.pack(">d", am_expected), \
                f"rec {i} actualOutputMult"
            gm_actual = rng.next_double()
            gm_expected = _hex_bits_to_double(expected["goodUnitsMult"])
            assert struct.pack(">d", gm_actual) == struct.pack(">d", gm_expected), \
                f"rec {i} goodUnitsMult"
            assert rng.next_int(3) == expected["failureCount"], f"rec {i} failureCount"
            assert rng.next_int(5) == expected["downtimeReason"], f"rec {i} downtimeReason"

    def test_all_seeds_mixed_pattern(self, java_reference):
        """Every seed in the fixture must reproduce its 5-record mixed sequence."""
        mismatches = []
        for seq in java_reference["random_sequences"]:
            seed = seq["seed"]
            rng = _JavaRandom(seed)
            for i, expected in enumerate(seq["mixed_records_5"]):
                checks = [
                    ("plannedRuntime", rng.next_int(8), expected["plannedRuntime"], "int"),
                    ("downtime", rng.next_double(), expected["downtime"], "double"),
                    ("theoreticalOutput", rng.next_int(100), expected["theoreticalOutput"], "int"),
                    ("actualOutputMult", rng.next_double(), expected["actualOutputMult"], "double"),
                    ("goodUnitsMult", rng.next_double(), expected["goodUnitsMult"], "double"),
                    ("failureCount", rng.next_int(3), expected["failureCount"], "int"),
                    ("downtimeReason", rng.next_int(5), expected["downtimeReason"], "int"),
                ]
                for name, actual, exp, kind in checks:
                    if kind == "int":
                        if actual != exp:
                            mismatches.append({"seed": seed, "rec": i,
                                               "field": name,
                                               "expected": exp, "actual": actual})
                    else:  # double via hex bits
                        e = _hex_bits_to_double(exp)
                        if struct.pack(">d", actual) != struct.pack(">d", e):
                            mismatches.append({"seed": seed, "rec": i,
                                               "field": name,
                                               "expected_hex": exp, "actual": actual})
        assert not mismatches, f"mixed pattern mismatches: {mismatches[:3]}"


