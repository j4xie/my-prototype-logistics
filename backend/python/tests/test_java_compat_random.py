# _JavaRandom.next_double — bit-exact via raw bits
# ---------------------------------------------------------------------------


class TestNextDouble:
    def test_range_is_unit_interval(self):
        rng = _JavaRandom(123)
        for _ in range(100):
            d = rng.next_double()
            assert 0.0 <= d < 1.0

    def test_seed_zero_first_thirty_bit_exact(self, java_reference):
        seq = java_reference["random_sequences"][0]
        assert seq["seed"] == 0
        expected_hex = seq["next_double_30"]
        rng = _JavaRandom(0)
        for i, hex_bits in enumerate(expected_hex):
            expected = _hex_bits_to_double(hex_bits)
            actual = rng.next_double()
            # Bit-exact comparison via raw bits.
            ea = struct.pack(">d", expected)
            ab = struct.pack(">d", actual)
            assert ea == ab, (
                f"next_double[{i}] differs: expected={expected!r} (bits={hex_bits}) "
                f"actual={actual!r} (bits={ab.hex()})"
            )

    def test_all_seeds_bit_exact(self, java_reference):
        mismatches = []
        for seq in java_reference["random_sequences"]:
            seed = seq["seed"]
            rng = _JavaRandom(seed)
            for i, hex_bits in enumerate(seq["next_double_30"]):
                expected = _hex_bits_to_double(hex_bits)
                actual = rng.next_double()
                if struct.pack(">d", expected) != struct.pack(">d", actual):
                    mismatches.append({"seed": seed, "i": i,
                                       "expected_hex": hex_bits,
                                       "actual": actual})
                    break  # one fail per seed is enough to flag drift
        assert not mismatches, f"next_double mismatches: {mismatches[:3]}"


