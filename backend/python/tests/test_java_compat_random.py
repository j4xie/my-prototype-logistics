"""Bit-exact parity tests for _java_string_hashcode + _JavaRandom.

These helpers mirror Java's ``java.lang.String.hashCode()`` (signed 32-bit
polynomial hash) and ``java.util.Random`` (48-bit LCG) so Python ports of
SmartBI mock-data generators (production / quality endpoints, T6.6 Phase B)
can produce byte-shape-identical JSON without spinning up a JVM.

Golden values come from ``tests/fixtures/java-random-reference.json``,
generated by ``tests/fixtures/JavaRandomReferenceDump.java`` running on
Azul JDK 21.0.10. Re-generate via:

    java backend/python/tests/fixtures/JavaRandomReferenceDump.java \\
      > backend/python/tests/fixtures/java-random-reference.json

The fixture stores ``next_double`` results as 16-char hex of
``Double.doubleToRawLongBits`` to preserve the full 53-bit mantissa across
JSON round-trips.
"""
from __future__ import annotations

import json
import struct
from pathlib import Path

import pytest

from smartbi_compat._java_compat import _JavaRandom, _java_string_hashcode

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "java-random-reference.json"


@pytest.fixture(scope="module")
def java_reference():
    with FIXTURE_PATH.open("r", encoding="utf-8") as f:
        return json.load(f)


def _hex_bits_to_double(hex_bits: str) -> float:
    """Convert 16-char hex of doubleToRawLongBits back to Python float."""
    raw = struct.pack(">Q", int(hex_bits, 16))
    return struct.unpack(">d", raw)[0]


# ---------------------------------------------------------------------------
# _java_string_hashcode
# ---------------------------------------------------------------------------


class TestJavaStringHashcode:
    def test_empty_string(self):
        assert _java_string_hashcode("") == 0

    def test_single_char_ascii(self):
        # Java: h = 31*0 + 'a' = 97
        assert _java_string_hashcode("a") == 97

    def test_two_chars(self):
        # h = 31*0 + 'a' = 97;  h = 31*97 + 'b' = 3007 + 98 = 3105
        assert _java_string_hashcode("ab") == 3105

    def test_factory_id_f001(self):
        # Real Java JDK 21 reference value (PR #199 §3.3 quoted 2153483 —
        # that was a spec drift; actual is 2133035).
        assert _java_string_hashcode("F001") == 2133035

    def test_well_known_collision(self):
        # 'AaAa' and 'BBBB' both hash to 2031744 in Java — the canonical
        # textbook collision used to demonstrate the polynomial's weakness.
        assert _java_string_hashcode("AaAa") == 2031744
        assert _java_string_hashcode("BBBB") == 2031744

    def test_returns_signed_int32_negative(self):
        # FOOD_3101_001 / TEST_0000_001 hash to negative int32 in Java.
        assert _java_string_hashcode("FOOD_3101_001") == -1714125422
        assert _java_string_hashcode("TEST_0000_001") == -2086637953

    def test_chinese_bmp_chars(self):
        # 中=0x4E2D=20013, 文=0x6587=25991
        # h = 31*0 + 20013 = 20013
        # h = 31*20013 + 25991 = 620403 + 25991 = 646394
        assert _java_string_hashcode("中文") == 646394

    def test_chinese_three_chars(self):
        assert _java_string_hashcode("白垩纪") == 29878110

    def test_all_fixture_values(self, java_reference):
        """Sweep every golden value from the Java reference dump."""
        mismatches = []
        for s, expected in java_reference["hashcode"].items():
            actual = _java_string_hashcode(s)
            if actual != expected:
                mismatches.append((s, expected, actual))
        assert not mismatches, f"hashcode mismatches: {mismatches}"

    def test_signed_int32_bounds(self, java_reference):
        """Every output must fit in signed int32 [-2^31, 2^31-1]."""
        lo, hi = -(2**31), (2**31) - 1
        for s in java_reference["hashcode"]:
            h = _java_string_hashcode(s)
            assert lo <= h <= hi, f"{s!r} hashed to {h}, out of int32 range"


