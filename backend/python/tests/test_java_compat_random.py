class TestFactoryIdSeed:
    """Real production usage: seed = factoryId.hashCode(). Verifies the
    composition of _java_string_hashcode + _JavaRandom matches Java behavior."""

    @pytest.mark.parametrize(
        "factory_id, expected_first_int_8",
        [
            # First nextInt(8) value for each factory_id, captured from the
            # fixture's random_sequences entries seeded by hashCode("F001"), etc.
            # Values verified via: jq '.random_sequences[] | select(.seed == HASH).next_int_8[0]'
            ("F001", 0),
            ("F002", 0),
            ("F999", 2),
            ("RES_3101_001", 2),
            ("RES_GML_001", 0),
        ],
    )
    def test_factory_seed_matches(self, factory_id, expected_first_int_8, java_reference):
        seed = _java_string_hashcode(factory_id)
        rng = _JavaRandom(seed)
        first = rng.next_int(8)
        # Cross-check against the fixture's recorded sequence for this seed.
        seq = next(s for s in java_reference["random_sequences"] if s["seed"] == seed)
        assert first == seq["next_int_8"][0]
        assert first == expected_first_int_8
